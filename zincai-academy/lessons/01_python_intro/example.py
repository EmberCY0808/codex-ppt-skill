# 第一课示例：计算相对第 1 圈的容量保持率。
# 数据来源：人为构造的模拟教学数据，不来自真实实验、文献或分子计算。
# 教学样品：Teaching-Organic-A。
# 第 1 圈和第 100 圈的电流密度均为 0.2 A/g。
# 教学假定：两次记录的电解液、电压窗口及其他测试条件一致。
# 两项均为放电比容量，单位为 mAh/g，按同一有机活性物质质量基准归一化。

# 保存第 1 圈的比容量，作为参考值。
initial_capacity = 200.0

# 保存第 100 圈的比容量。
later_capacity = 180.0

# 相同单位相除后抵消；乘以 100，得到容量保持率的百分数数值。
retention_percent = later_capacity / initial_capacity * 100

# 输出数据来源和带说明的结果。
print("数据来源：模拟教学数据，非真实实验数据。")
print("相对第 1 圈的容量保持率（%）：", retention_percent)

